# -*- coding: utf-8 -*-
"""Build the Intel 8751 firmware: generate the cipher tables, assemble
mcu51.asm with as31, check the layout.  build() -> (image, labels)
usage: build51.py [output file]"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def k1(i): return 0x7E if i & 2 else 0x12
def k2(i): return 0x5E if i & 2 else 0xAE


PTAB = [((0x80 - (i ^ k1(i))) if i & 1 else (i ^ k2(i))) & 0xFF for i in range(256)]
FTAB = [((0xA0 if v & 0x20 else 0x60) - v - (0 if v & 1 else 2)) & 0xFF for v in range(256)]


def tables_text():
    out = ["; cipher tables, generated by build51.py",
           "; odd index : payload = c + PTAB[i]      decrypt = 60h - PTAB[i] - c",
           "; even index: payload = FTAB[c ^ PTAB[i]] decrypt = c ^ PTAB[i]",
           "tab_p:"]
    for r in range(0, 256, 16):
        out.append("        .db     " + ",".join(f"0{b:02X}h" for b in PTAB[r:r + 16]))
    out.append("tab_f:")
    for r in range(0, 256, 16):
        out.append("        .db     " + ",".join(f"0{b:02X}h" for b in FTAB[r:r + 16]))
    return "\n".join(out) + "\n"


def build():
    src = open(os.path.join(HERE, "mcu51.asm")).read()
    src = src.replace("        .inc    tables51.inc\n", tables_text())
    with tempfile.TemporaryDirectory() as d:
        asm = os.path.join(d, "mcu51.asm")
        open(asm, "w").write(src)
        r = subprocess.run(["as31", "-l", "-Fbin", "-O" + os.path.join(d, "mcu51.bin"), asm],
                           capture_output=True, text=True)
        if r.returncode or "rror" in r.stdout + r.stderr or "arning" in r.stdout + r.stderr:
            raise RuntimeError("as31:\n" + r.stdout + r.stderr)
        img = open(os.path.join(d, "mcu51.bin"), "rb").read()
        lst = open(os.path.join(d, "mcu51.lst")).read()
    labels, pending, code_end = {}, [], 0
    for line in lst.splitlines():
        m = re.match(r"^([0-9A-Fa-f]{4}):((?:\s[0-9A-Fa-f]{2})*)\s+(?:([A-Za-z_][A-Za-z0-9_]*):)?", line)
        if m:
            addr, nbytes = int(m.group(1), 16), len(m.group(2).split())
            if m.group(3): labels[m.group(3)] = addr
            if nbytes:                       # only lines that emit bytes fix pending labels
                for p in pending: labels[p] = addr
                pending = []
                if addr < 0x0E00: code_end = max(code_end, addr + nbytes)
            continue
        m = re.match(r"^\s+([A-Za-z_][A-Za-z0-9_]*):", line)
        if m: pending.append(m.group(1))
    labels["code_end"] = code_end
    img = img + b"\xff" * (0x1000 - len(img))
    assert len(img) == 0x1000, f"image {len(img)} bytes"
    assert labels["tab_p"] == 0x0E00 and labels["tab_f"] == 0x0F00, "tables misplaced"
    assert labels["code_end"] <= 0x0E00, f"code overlaps the tables: ends at {labels['code_end']:#06x}"
    return img, labels


if __name__ == "__main__":
    img, labels = build()
    print(f"firmware 8751 : image 4096 octets ; code {labels['code_end']} octets "
          f"({0x0E00 - labels['code_end']} libres avant les tables), tables 512 octets")
    if len(sys.argv) > 1:
        open(sys.argv[1], "wb").write(img)
        print(f"écrit: {sys.argv[1]}")
