# -*- coding: utf-8 -*-
"""Generate firmware/drawloop.s: the hot loop that decodes one tile stream of a
level background and writes its cells to the tilemap.

Speed tricks (the 6801 has a single index register):
  - X walks the data ROM; the STACK POINTER walks the cipher table PTAB: the
    cipher index of consecutive bytes goes up by one, so PULB both fetches
    PTAB[i] and moves to the next entry.  Interrupts are never enabled and the
    loop makes no calls, so borrowing SP is safe; it is restored on exit.
  - When the low address byte wraps (page crossing) the index jumps by 2, not
    1: an extra INS skips one table entry.  The crossing is detected by
    comparing X with the next page boundary XPB, which also catches the end of
    the data ROM (DEND is a page boundary).
  - Byte parity (odd: c + PTAB[i], even: F(c ^ PTAB[i])) and cell parity
    (left / right tile of the pair) are encoded in the code position: four
    states S<E><Q>, E = parity expected for the next byte, Q = next cell.
  - A half is only valid if every stream has exactly the expected number of
    cells.  No counter: the last cell is the right cell of the last row, detected
    when the write pointer moves past the end row (WENDH).  A stream ending
    earlier, or one more cell afterwards (states F), makes the half invalid,
    which is exactly what the HLE ends up with; so there is no 64-cell counter.
  - SP is kept inside PTAB (+ a 128-entry copy) by a check after each
    attribute token; between two tokens at most ~34 entries are consumed.
Exits: dl_end (stream finished: 00 token or end of ROM), dl_bad (invalid).
"""
import os

out = []
n = [0]


def emit(s=""):
    out.append(s)


def lab():
    n[0] += 1
    return f"zl{n[0]}"


def decode(parity):
    """A = cipher byte, B = PTAB[i]  ->  A = payload-decoded byte."""
    if parity:                      # odd index: c + PTAB[i]
        emit("        ABA")
        return
    a, b = lab(), lab()             # even index: F(c ^ PTAB[i]), F inlined
    emit("        STAB STMP")
    emit("        EORA STMP           ; v = c ^ PTAB[i]")
    emit("        TAB")
    emit("        NEGA")
    emit("        ADDA #$60           ; $60 - v")
    emit("        BITB #$20")
    emit(f"        BEQ  {a}")
    emit("        ADDA #$40           ; $A0 - v")
    emit(f"{a}:")
    emit("        BITB #$01")
    emit(f"        BNE  {b}")
    emit("        SUBA #$02")
    emit(f"{b}:")


def fetch():
    emit("        LDAA 0,X")
    emit("        INX")
    emit("        PULB")


def cross(bad_label):
    """X is at the page boundary XPB: end of ROM, or skip one table entry."""
    emit("        CPX  #DEND")
    emit(f"        LBEQ {bad_label}")
    emit("        INS")
    emit("        INC  XPBH")


def wrapcheck():
    ok = lab()
    emit("        STS  SPTH")
    emit("        LDAA SPTH")
    emit("        CMPA #PTABH+1")
    emit(f"        BCS  {ok}")
    emit("        DEC  SPTH           ; back into the first copy of PTAB")
    emit("        LDS  SPTH")
    emit(f"{ok}:")


def write_cell(q):
    emit("        STX  XSH")
    emit("        LDX  WPH")
    if q == 0:
        emit("        STAA 0,X            ; left tile + attribute")
        emit("        LDAA ATTR")
        emit("        STAA 1,X")
        emit("        LDX  XSH")
    else:
        emit("        STAA 2,X            ; right tile + attribute")
        emit("        LDAA ATTR")
        emit("        STAA 3,X")
        emit("        LDX  XSH")
        emit("        LDAA WPH            ; next tile row: +512")
        emit("        ADDA #2")
        emit("        STAA WPH")
        emit("        CMPA WENDH          ; past the last row: expected length reached")


emit("; -----------------------------------------------------------------------------")
emit("; Level stream hot loop - GENERATED by gen_drawloop.py, do not edit by hand.")
emit("; Entered from draw.s with X = data pointer, SP = PTAB - 1 + index.")
emit("; -----------------------------------------------------------------------------")
emit()
for E in (0, 1):
    for Q in (0, 1):
        s = f"{E}{Q}"
        emit(f"; ---- state: next byte {'odd' if E else 'even'} index, next cell {'right' if Q else 'left'}")
        emit(f"S{s}:")
        emit("        CPX  XPBH")
        emit(f"        LBEQ X{s}")
        fetch()
        emit(f"D{s}:")
        decode(E)
        emit("        CMPA #$01")
        emit(f"        LBLS T{s}")
        write_cell(Q)
        if Q:
            emit(f"        LBEQ F{1 - E}")
        emit(f"        JMP  S{1 - E}{1 - Q}")
        emit(f"X{s}:                           ; page crossing: this byte has parity {1 - E}")
        cross("dl_bad")                 # ROM ends before the expected length
        fetch()
        emit(f"        JMP  D{1 - E}{Q}")
        emit(f"T{s}:                           ; token 00 / 01 <attr>")
        emit("        TSTA")
        emit("        LBEQ dl_bad         ; stream shorter than expected")
        emit("        CPX  XPBH")
        emit(f"        LBEQ XA{s}")
        fetch()
        emit(f"TA{s}:                          ; attribute byte fetched, parity {1 - E}")
        decode(1 - E)
        emit("        STAA ATTR")
        wrapcheck()
        emit(f"        JMP  S{E}{Q}")
        emit(f"XA{s}:                          ; attribute byte across a page boundary: parity {E},")
        cross("dl_bad")                 # same tail as T<1-E><Q> after its fetch
        fetch()
        emit(f"        JMP  TA{1 - E}{Q}")
        emit()

for E in (0, 1):
    emit(f"; ---- full: expected length reached, next byte {'odd' if E else 'even'}; one more cell = invalid")
    emit(f"F{E}:")
    emit("        CPX  XPBH")
    emit(f"        LBEQ FX{E}")
    fetch()
    emit(f"FD{E}:")
    decode(E)
    emit("        CMPA #$01")
    emit("        LBHI dl_bad")
    emit("        TSTA")
    emit("        LBEQ dl_end")
    emit("        CPX  XPBH")
    emit(f"        LBEQ FXA{E}")
    emit("        INX                 ; skip the attribute byte")
    emit("        INS")
    wrapcheck()
    emit(f"        JMP  F{E}")
    emit(f"FX{E}:")
    cross("dl_end")
    fetch()
    emit(f"        JMP  FD{1 - E}")
    emit(f"FXA{E}:")
    cross("dl_bad")
    emit("        INX")
    emit("        INS")
    wrapcheck()
    emit(f"        JMP  F{1 - E}")
    emit()

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "drawloop.s")
open(path, "w").write("\n".join(out) + "\n")
print(f"wrote {path}")
