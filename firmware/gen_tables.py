# -*- coding: utf-8 -*-
"""Generate firmware/tables.s: lookup tables that turn the MCU's address-local
cipher + payload transform into one or two table reads per byte.

For a data-ROM byte c whose cipher index is i = (addr_lo + addr_hi) & 0xFF:

  decrypt:  i odd : v = (i ^ K1(i)) - 0x20 - c      K1 = 0x7E if i&2 else 0x12
            i even: v = c ^ i ^ K2(i)               K2 = 0x5E if i&2 else 0xAE
  payload:  i odd : out = 0x60 - v
            i even: out = F(v) = (0xA0 if v&0x20 else 0x60) - v - (0 if v&1 else 2)

which folds into
  payload, i odd : out = c + PTAB[i]          PTAB[i] = 0x80 - (i ^ K1)
  payload, i even: out = FTAB[c ^ PTAB[i]]    PTAB[i] = i ^ K2
  decrypt, i odd : v   = DTAB[i] - c          DTAB[i] = (i ^ K1) - 0x20
  decrypt, i even: v   = c ^ PTAB[i]

Note: when reading sequentially the index does NOT simply increment: at a page
crossing (low byte FF -> 00, high byte + 1) it jumps by 2.  The firmware
therefore recomputes it from the read pointer for every byte.
"""
import os

def k1(i): return 0x7E if i & 2 else 0x12
def k2(i): return 0x5E if i & 2 else 0xAE

PTAB = [((0x80 - (i ^ k1(i))) if i & 1 else (i ^ k2(i))) & 0xFF for i in range(256)]
DTAB = [(((i ^ k1(i)) - 0x20) if i & 1 else 0) & 0xFF for i in range(256)]
FTAB = [((0xA0 if v & 0x20 else 0x60) - v - (0 if v & 1 else 2)) & 0xFF for v in range(256)]

def emit(name, tab, comment):
    out = [f"; {comment}", f"{name}:"]
    for r in range(0, 256, 16):
        out.append("        .BYTE " + ",".join(f"${b:02X}" for b in tab[r:r + 16]))
    return "\n".join(out) + "\n"

text = ("; -----------------------------------------------------------------------------\n"
        "; Cipher lookup tables - GENERATED by gen_tables.py, do not edit by hand.\n"
        "; -----------------------------------------------------------------------------\n\n"
        + emit("PTAB", PTAB, "payload: odd i -> add, even i -> xor (then FTAB)") + "\n"
        + emit("DTAB", DTAB, "decrypt, odd i: v = DTAB[i] - c") + "\n"
        + emit("FTAB", FTAB, "payload second stage for even i, indexed by v"))
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables.s")
open(path, "w").write(text)
print(f"wrote {path} (768 bytes of tables)")
